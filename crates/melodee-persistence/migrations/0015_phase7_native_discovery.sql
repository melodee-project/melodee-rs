-- Phase 7 native discovery, charts, playback backend, and theme authority.
-- (ADR-0123, ADR-0127; PRD-DISCOVERY-001..003, PRD-PARTY-003,
-- PRD-USER-001, PRD-API-M1-004..006).
--
-- Additive only. Binary downgrade retains these tables. Full schema rollback
-- restores a verified pre-0015 backup into a new database. These projections
-- reference catalog/user facts and never rewrite or delete catalog media.

CREATE TABLE native_charts (
    id uuid PRIMARY KEY,
    public_api_id uuid NOT NULL UNIQUE,
    legacy_numeric_id integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    slug text NOT NULL UNIQUE,
    title text NOT NULL,
    source_name text NULL,
    source_url text NULL,
    chart_year integer NULL,
    description text NULL,
    tags text[] NOT NULL DEFAULT '{}',
    is_visible boolean NOT NULL DEFAULT true,
    is_generated_playlist_enabled boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT native_charts_id_v7 CHECK (COALESCE(uuid_extract_version(id) = 7, false)),
    CONSTRAINT native_charts_text CHECK (
        btrim(slug) <> '' AND btrim(title) <> ''
        AND char_length(slug) <= 255 AND char_length(title) <= 500
        AND (source_name IS NULL OR char_length(source_name) <= 500)
        AND (source_url IS NULL OR char_length(source_url) <= 4096)
        AND (description IS NULL OR char_length(description) <= 10000)
    ),
    CONSTRAINT native_charts_time CHECK (created_at <= updated_at)
);

CREATE INDEX native_charts_visible_idx
    ON native_charts (created_at DESC, public_api_id) WHERE is_visible;

CREATE TRIGGER native_charts_public_api_id_immutable
BEFORE UPDATE OF public_api_id ON native_charts
FOR EACH ROW EXECUTE FUNCTION reject_public_api_id_rewrite();

CREATE TABLE native_chart_items (
    chart_id uuid NOT NULL REFERENCES native_charts (id) ON DELETE CASCADE,
    rank integer NOT NULL,
    artist_name text NOT NULL,
    release_title text NOT NULL,
    release_year integer NULL,
    linked_artist_id uuid NULL REFERENCES artists (id) ON DELETE SET NULL,
    linked_release_id uuid NULL REFERENCES releases (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (chart_id, rank),
    CONSTRAINT native_chart_items_rank CHECK (rank > 0),
    CONSTRAINT native_chart_items_text CHECK (
        btrim(artist_name) <> '' AND btrim(release_title) <> ''
        AND char_length(artist_name) <= 500 AND char_length(release_title) <= 500
    )
);

CREATE INDEX native_chart_items_links_idx
    ON native_chart_items (linked_release_id, linked_artist_id, chart_id, rank);

CREATE TABLE native_track_audio_features (
    track_id uuid PRIMARY KEY REFERENCES tracks (id) ON DELETE CASCADE,
    tempo double precision NOT NULL,
    musical_key text NULL,
    mode text NULL,
    time_signature integer NOT NULL DEFAULT 4,
    acousticness double precision NOT NULL DEFAULT 0.5,
    danceability double precision NOT NULL DEFAULT 0.5,
    energy double precision NOT NULL DEFAULT 0.5,
    instrumentalness double precision NOT NULL DEFAULT 0.5,
    liveness double precision NOT NULL DEFAULT 0.2,
    loudness double precision NOT NULL DEFAULT -10,
    speechiness double precision NOT NULL DEFAULT 0.1,
    valence double precision NOT NULL DEFAULT 0.5,
    updated_at timestamptz NOT NULL,
    CONSTRAINT native_track_audio_features_finite CHECK (
        tempo BETWEEN 0 AND 1000
        AND time_signature BETWEEN 1 AND 32
        AND acousticness BETWEEN 0 AND 1
        AND danceability BETWEEN 0 AND 1
        AND energy BETWEEN 0 AND 1
        AND instrumentalness BETWEEN 0 AND 1
        AND liveness BETWEEN 0 AND 1
        AND loudness BETWEEN -1000 AND 1000
        AND speechiness BETWEEN 0 AND 1
        AND valence BETWEEN 0 AND 1
    )
);

CREATE INDEX native_track_audio_features_tempo_idx
    ON native_track_audio_features (tempo, track_id);

CREATE TABLE native_playback_backend_state (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    enabled boolean NOT NULL DEFAULT false,
    initialized boolean NOT NULL DEFAULT false,
    is_playing boolean NOT NULL DEFAULT false,
    position_seconds double precision NOT NULL DEFAULT 0,
    volume double precision NULL,
    current_track_id uuid NULL REFERENCES tracks (id) ON DELETE SET NULL,
    session_public_api_id uuid NULL UNIQUE,
    last_heartbeat_at timestamptz NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT native_playback_backend_position CHECK (position_seconds >= 0),
    CONSTRAINT native_playback_backend_volume CHECK (
        volume IS NULL OR volume BETWEEN 0 AND 1
    )
);

CREATE TABLE native_playback_endpoints (
    id uuid PRIMARY KEY,
    public_api_id uuid NOT NULL UNIQUE,
    owner_user_id uuid NULL REFERENCES native_users (id) ON DELETE SET NULL,
    name text NOT NULL,
    endpoint_type text NOT NULL,
    is_shared boolean NOT NULL DEFAULT false,
    room text NULL,
    capabilities_json text NULL,
    last_seen_at timestamptz NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT native_playback_endpoints_id_v7 CHECK (
        COALESCE(uuid_extract_version(id) = 7, false)
    ),
    CONSTRAINT native_playback_endpoints_text CHECK (
        btrim(name) <> '' AND btrim(endpoint_type) <> ''
        AND char_length(name) <= 500 AND char_length(endpoint_type) <= 100
        AND (room IS NULL OR char_length(room) <= 500)
        AND (capabilities_json IS NULL OR char_length(capabilities_json) <= 10000)
    ),
    CONSTRAINT native_playback_endpoints_time CHECK (created_at <= updated_at)
);

CREATE TRIGGER native_playback_endpoints_public_api_id_immutable
BEFORE UPDATE OF public_api_id ON native_playback_endpoints
FOR EACH ROW EXECUTE FUNCTION reject_public_api_id_rewrite();

CREATE UNIQUE INDEX native_playback_endpoints_one_system_type_idx
    ON native_playback_endpoints (endpoint_type)
    WHERE owner_user_id IS NULL;

-- Theme contents are database-owned bytes so request paths never select an
-- arbitrary filesystem location. The bounded size applies per asset.
CREATE TABLE native_themes (
    id text PRIMARY KEY,
    name text NOT NULL,
    author text NOT NULL,
    version text NOT NULL,
    description text NULL,
    is_built_in boolean NOT NULL DEFAULT false,
    preview_image text NULL,
    has_warnings boolean NOT NULL DEFAULT false,
    warning_details text NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT native_themes_id CHECK (
        id ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$'
    ),
    CONSTRAINT native_themes_text CHECK (
        btrim(name) <> '' AND btrim(author) <> '' AND btrim(version) <> ''
        AND char_length(name) <= 500 AND char_length(author) <= 500
        AND char_length(version) <= 100
        AND (description IS NULL OR char_length(description) <= 10000)
        AND (preview_image IS NULL OR char_length(preview_image) <= 500)
        AND (warning_details IS NULL OR char_length(warning_details) <= 10000)
    ),
    CONSTRAINT native_themes_time CHECK (created_at <= updated_at)
);

CREATE TABLE native_theme_assets (
    theme_id text NOT NULL REFERENCES native_themes (id) ON DELETE CASCADE,
    relative_path text NOT NULL,
    mime_type text NOT NULL,
    bytes bytea NOT NULL,
    PRIMARY KEY (theme_id, relative_path),
    CONSTRAINT native_theme_assets_path CHECK (
        btrim(relative_path) <> ''
        AND relative_path !~ '(^/|(^|/)\.\.(/|$)|\\)'
        AND char_length(relative_path) <= 1000
    ),
    CONSTRAINT native_theme_assets_mime CHECK (
        mime_type IN (
            'text/css', 'application/json', 'image/png', 'image/jpeg',
            'image/x-icon', 'image/svg+xml', 'font/woff', 'font/woff2'
        )
    ),
    CONSTRAINT native_theme_assets_size CHECK (octet_length(bytes) BETWEEN 1 AND 10485760)
);

